package com.group.usbshield.server.device;

import org.junit.jupiter.api.Test;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import javax.sql.DataSource;
import java.sql.Connection;
import java.sql.ResultSet;
import java.sql.Statement;
import java.util.UUID;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

/** Checks legacy data remediation before Hibernate adds a hash uniqueness constraint. */
class UsbCatalogUpgradeTest {
    private DataSource source() {
        return new DriverManagerDataSource("jdbc:h2:mem:upgrade-" + UUID.randomUUID()
                + ";DB_CLOSE_DELAY=-1", "sa", "");
    }

    private void seed(DataSource source) throws Exception {
        try (Connection connection = source.getConnection(); Statement sql = connection.createStatement()) {
            sql.execute("CREATE TABLE usb_devices (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "device_hash VARCHAR(255), vendor_id VARCHAR(10), product_id VARCHAR(10))");
        }
    }

    @Test
    void legacyEmptyAndWhitespaceHashesBecomeNullWithoutDeletingRows() throws Exception {
        DataSource ds = source();
        seed(ds);
        try (Connection connection = ds.getConnection(); Statement sql = connection.createStatement()) {
            sql.execute("INSERT INTO usb_devices (device_hash) VALUES (''), ('   '), ('stable-hash')");
        }
        UsbCatalogUpgrade.normalizeAndValidate(ds);
        UsbCatalogUpgrade.normalizeAndValidate(ds); // idempotent across restarts
        try (Connection connection = ds.getConnection(); Statement sql = connection.createStatement()) {
            try (ResultSet rows = sql.executeQuery("SELECT COUNT(*), COUNT(device_hash) FROM usb_devices")) {
                assertThat(rows.next()).isTrue();
                assertThat(rows.getLong(1)).isEqualTo(3);
                assertThat(rows.getLong(2)).isEqualTo(1);
            }
        }
    }

    @Test
    void duplicateNonblankHashesStopUpgradeWithoutMergingOrDroppingEvidence() throws Exception {
        DataSource ds = source();
        seed(ds);
        try (Connection connection = ds.getConnection(); Statement sql = connection.createStatement()) {
            sql.execute("INSERT INTO usb_devices (device_hash) VALUES ('stable'), ('stable'), ('')");
        }
        assertThatThrownBy(() -> UsbCatalogUpgrade.normalizeAndValidate(ds))
                .isInstanceOf(IllegalStateException.class)
                .hasMessageContaining("duplicate nonblank device hashes");
        try (Connection connection = ds.getConnection(); Statement sql = connection.createStatement();
             ResultSet rows = sql.executeQuery("SELECT COUNT(*) FROM usb_devices WHERE device_hash = 'stable'")) {
            assertThat(rows.next()).isTrue();
            assertThat(rows.getInt(1)).isEqualTo(2);
        }
    }

    @Test
    void freshDatabaseIsLeftForHibernateToInitialize() {
        UsbCatalogUpgrade.normalizeAndValidate(source());
    }
}

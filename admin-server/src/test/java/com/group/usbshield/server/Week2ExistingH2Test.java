package com.group.usbshield.server;
import com.group.usbshield.server.endpoint.*;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.test.context.DynamicPropertyRegistry;
import org.springframework.test.context.DynamicPropertySource;
import java.sql.*;
import java.nio.file.*;
import static org.assertj.core.api.Assertions.assertThat;
@SpringBootTest(properties="spring.jpa.hibernate.ddl-auto=update")
class Week2ExistingH2Test {
    static String url;
    @DynamicPropertySource static void legacyDatabase(DynamicPropertyRegistry registry) throws Exception {
        Path directory=Path.of("target","week2-migration-"+java.util.UUID.randomUUID());
        Files.createDirectories(directory);
        url="jdbc:h2:file:"+directory.toAbsolutePath().toString().replace('\\','/')+"/legacy;DB_CLOSE_ON_EXIT=FALSE";
        try(var c=DriverManager.getConnection(url,"sa","");var sql=c.createStatement()){
            sql.execute("CREATE TABLE endpoints (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, endpoint_id VARCHAR(100) NOT NULL UNIQUE, hostname VARCHAR(150) NOT NULL, machine_id VARCHAR(100), ip_address VARCHAR(50), status VARCHAR(30) NOT NULL, last_seen TIMESTAMP WITH TIME ZONE, policy_version BIGINT NOT NULL, applied_policy_version BIGINT NOT NULL)");
            sql.execute("INSERT INTO endpoints(endpoint_id,hostname,machine_id,status,policy_version,applied_policy_version) VALUES('LEGACY-PC','legacy','legacy-machine','OFFLINE',7,6)");
        }
        registry.add("spring.datasource.url",()->url);
    }
    @Autowired EndpointRepository endpoints;
    @Test void existingWeek1EndpointSurvivesAdditiveSchemaUpdateAndPersistsCredential() throws Exception {
        var endpoint=endpoints.findByEndpointId("LEGACY-PC").orElseThrow();
        assertThat(endpoint.getPolicyVersion()).isEqualTo(7L);
        assertThat(endpoint.getAppliedPolicyVersion()).isEqualTo(6L);
        assertThat(endpoint.getAgentTokenHash()).isNull();
        endpoint.setAgentTokenHash("test-hash-only");endpoints.saveAndFlush(endpoint);
        try(var c=DriverManager.getConnection(url,"sa","");var sql=c.createStatement();var rows=sql.executeQuery("SELECT agent_token_hash, policy_version FROM endpoints WHERE endpoint_id='LEGACY-PC'")){
            assertThat(rows.next()).isTrue();assertThat(rows.getString(1)).isEqualTo("test-hash-only");assertThat(rows.getLong(2)).isEqualTo(7);
        }
    }
}

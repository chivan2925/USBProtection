package com.group.usbshield.server.device;

import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.context.DynamicPropertyRegistry;
import org.springframework.test.context.DynamicPropertySource;

import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.DriverManager;
import java.sql.Statement;
import java.sql.PreparedStatement;
import java.util.UUID;

import static org.assertj.core.api.Assertions.assertThat;

/** Verifies the upgrade runs before Hibernate tries to add UNIQUE(device_hash). */
@SpringBootTest(properties = "spring.jpa.hibernate.ddl-auto=update")
class UsbCatalogUpgradeStartupIntegrationTest {
    private static String url;

    @DynamicPropertySource
    static void legacyDatabase(DynamicPropertyRegistry properties) throws Exception {
        Path directory = Path.of("target", "usb-catalog-preflight-" + UUID.randomUUID());
        Files.createDirectories(directory);
        url = "jdbc:h2:file:" + directory.toAbsolutePath().toString().replace('\\', '/')
                + "/legacy;DB_CLOSE_ON_EXIT=FALSE";
        try (var connection = DriverManager.getConnection(url, "sa", "");
             Statement sql = connection.createStatement()) {
            sql.execute("CREATE TABLE usb_devices (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "vendor_id VARCHAR(10) NOT NULL, product_id VARCHAR(10) NOT NULL, "
                    + "device_hash VARCHAR(255), created_at TIMESTAMP WITH TIME ZONE NOT NULL)");
            try (PreparedStatement insert = connection.prepareStatement(
                    "INSERT INTO usb_devices(vendor_id,product_id,device_hash,created_at) "
                    + "VALUES('1111','2222',?,CURRENT_TIMESTAMP())")) {
                for (String hash : new String[] {"", "   ", "\t", "\n", "\u2003", "stable-hash"}) {
                    insert.setString(1, hash);
                    insert.addBatch();
                }
                insert.executeBatch();
            }
        }
        properties.add("spring.datasource.url", () -> url);
    }

    @Autowired JdbcTemplate jdbc;

    @Test
    void legacyRowsAndUniqueIdentitySurviveStartup() {
        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM usb_devices", Integer.class)).isEqualTo(6);
        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM usb_devices WHERE device_hash IS NULL", Integer.class))
                .isEqualTo(5);
        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM usb_devices WHERE device_hash = 'stable-hash'", Integer.class))
                .isEqualTo(1);
    }
}

-- Initial PostgreSQL structure before the Phase 1 security/health fields.
-- NEW DATABASES: Flyway applies V1 then V2.
-- EXISTING UNVERSIONED DATABASES: back up and explicitly baseline at 1 first;
-- Flyway skips V1 and applies V2. NEVER enable baseline-on-migrate by default.
-- No DROP / TRUNCATE in the migration history.
CREATE TABLE admin_users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(100) NOT NULL UNIQUE,
    password_hash varchar(255) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL
);

CREATE TABLE endpoints (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    endpoint_id varchar(100) NOT NULL UNIQUE,
    hostname varchar(150) NOT NULL,
    machine_id varchar(100) UNIQUE,
    agent_token_hash varchar(255),
    ip_address varchar(50),
    operating_system varchar(100),
    active_username varchar(100),
    status varchar(30) NOT NULL,
    last_seen timestamp(6) with time zone,
    policy_version bigint NOT NULL,
    applied_policy_version bigint NOT NULL
);
CREATE UNIQUE INDEX idx_endpoint_id ON endpoints (endpoint_id);
CREATE INDEX idx_machine_id ON endpoints (machine_id);

CREATE TABLE usb_devices (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vendor_id varchar(10) NOT NULL,
    product_id varchar(10) NOT NULL,
    serial_number varchar(150),
    device_hash varchar(255) UNIQUE,
    device_name varchar(255),
    device_interfaces varchar(100),
    created_at timestamp(6) with time zone NOT NULL
);
CREATE INDEX idx_usb_vid_pid ON usb_devices (vendor_id, product_id);

CREATE TABLE usb_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    endpoint_id varchar(100) NOT NULL,
    event_id varchar(36),
    payload_digest varchar(64),
    usb_device_id bigint,
    hostname varchar(150),
    linux_username varchar(100) NOT NULL,
    linux_uid bigint,
    session_id varchar(50),
    session_type varchar(50),
    seat varchar(50),
    event_type varchar(50) NOT NULL,
    decision varchar(50) NOT NULL,
    occurred_at timestamp(6) with time zone NOT NULL,
    received_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT uk_endpoint_event_key UNIQUE (endpoint_id, event_id)
);
CREATE INDEX idx_event_endpoint_time ON usb_events (endpoint_id, occurred_at);
CREATE INDEX idx_event_decision ON usb_events (decision);
CREATE INDEX idx_event_user ON usb_events (linux_username);

CREATE TABLE endpoint_whitelist_entries (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    endpoint_id varchar(100) NOT NULL,
    usb_device_id bigint,
    fingerprint_type varchar(50) NOT NULL,
    fingerprint_value varchar(255) NOT NULL,
    enabled boolean NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT uk_endpoint_fingerprint UNIQUE (endpoint_id, fingerprint_value)
);
CREATE INDEX idx_endpoint_whitelist ON endpoint_whitelist_entries (endpoint_id, enabled);
CREATE INDEX idx_endpoint_fingerprint ON endpoint_whitelist_entries (endpoint_id, fingerprint_value);

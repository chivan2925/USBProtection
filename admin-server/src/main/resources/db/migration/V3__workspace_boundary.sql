-- P1 clean-data migration. Preserve V1/V2 and reject unassigned operational data.
-- Legacy installations need a separately approved mapping/cutover.
LOCK TABLE endpoints, usb_devices, usb_events, endpoint_whitelist_entries IN ACCESS EXCLUSIVE MODE;
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM endpoints) OR EXISTS (SELECT 1 FROM usb_devices)
        OR EXISTS (SELECT 1 FROM usb_events) OR EXISTS (SELECT 1 FROM endpoint_whitelist_entries) THEN
        RAISE EXCEPTION 'P1 requires an empty operational schema or an approved legacy ownership migration';
    END IF;
END
$$;

CREATE TABLE workspaces (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_admin_id bigint NOT NULL UNIQUE REFERENCES admin_users(id),
    CONSTRAINT uk_workspace_owner UNIQUE (id, owner_admin_id)
);
INSERT INTO workspaces (owner_admin_id) SELECT id FROM admin_users;

ALTER TABLE endpoints
    ADD COLUMN workspace_id bigint NOT NULL REFERENCES workspaces(id),
    ADD COLUMN installation_id uuid NOT NULL UNIQUE,
    ADD COLUMN credential_generation bigint NOT NULL DEFAULT 0 CHECK (credential_generation >= 0),
    ADD CONSTRAINT uk_endpoint_workspace_key UNIQUE (workspace_id, endpoint_id);

ALTER TABLE usb_devices
    DROP CONSTRAINT usb_devices_device_hash_key,
    ADD COLUMN workspace_id bigint NOT NULL REFERENCES workspaces(id),
    ADD CONSTRAINT uk_device_workspace_hash UNIQUE (workspace_id, device_hash),
    ADD CONSTRAINT uk_device_workspace_key UNIQUE (workspace_id, id),
    ADD CONSTRAINT uk_device_workspace_id_hash UNIQUE (workspace_id, id, device_hash),
    ADD CONSTRAINT chk_catalog_hash CHECK (
        device_hash IS NULL OR (
            device_hash ~ '^[A-Za-z0-9+/=_:.-]{1,255}$'
            AND device_hash ~ '[A-Za-z0-9]'
            AND device_hash !~ '^[0-9A-Fa-f]{4}:[0-9A-Fa-f]{4}$'
        )
    );

ALTER TABLE usb_events
    ADD COLUMN workspace_id bigint NOT NULL,
    DROP CONSTRAINT uk_endpoint_event_key,
    ADD CONSTRAINT uk_endpoint_event_key UNIQUE (workspace_id, endpoint_id, event_id),
    ADD CONSTRAINT fk_event_workspace_endpoint FOREIGN KEY (workspace_id, endpoint_id)
        REFERENCES endpoints(workspace_id, endpoint_id),
    ADD CONSTRAINT fk_event_workspace_device FOREIGN KEY (workspace_id, usb_device_id)
        REFERENCES usb_devices(workspace_id, id);

ALTER TABLE endpoint_whitelist_entries
    ADD COLUMN workspace_id bigint NOT NULL,
    ALTER COLUMN usb_device_id SET NOT NULL,
    DROP CONSTRAINT uk_endpoint_fingerprint,
    ADD CONSTRAINT uk_endpoint_fingerprint UNIQUE (workspace_id, endpoint_id, fingerprint_value),
    ADD CONSTRAINT chk_policy_hash_only CHECK (fingerprint_type = 'HASH'),
    ADD CONSTRAINT fk_policy_workspace_endpoint FOREIGN KEY (workspace_id, endpoint_id)
        REFERENCES endpoints(workspace_id, endpoint_id),
    ADD CONSTRAINT fk_policy_workspace_device FOREIGN KEY (workspace_id, usb_device_id, fingerprint_value)
        REFERENCES usb_devices(workspace_id, id, device_hash);

CREATE TABLE enrollment_tickets (
    id uuid PRIMARY KEY,
    workspace_id bigint NOT NULL,
    endpoint_id varchar(100) NOT NULL,
    secret_digest varchar(64) NOT NULL,
    expires_at timestamp(6) with time zone NOT NULL,
    revoked boolean NOT NULL DEFAULT false,
    request_id uuid,
    claim_generation bigint,
    claim_credential_digest varchar(64),
    receipt_until timestamp(6) with time zone,
    CONSTRAINT fk_ticket_workspace_endpoint FOREIGN KEY (workspace_id, endpoint_id)
        REFERENCES endpoints(workspace_id, endpoint_id),
    CONSTRAINT uk_ticket_claim_credential UNIQUE (workspace_id, endpoint_id, claim_credential_digest),
    CONSTRAINT chk_ticket_receipt CHECK (
        (request_id IS NULL AND claim_generation IS NULL AND claim_credential_digest IS NULL AND receipt_until IS NULL) OR
        (request_id IS NOT NULL AND claim_generation IS NOT NULL AND claim_credential_digest IS NOT NULL AND receipt_until IS NOT NULL)
    )
);
CREATE INDEX idx_ticket_endpoint ON enrollment_tickets (workspace_id, endpoint_id);

CREATE TABLE admin_audit (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id bigint NOT NULL,
    actor_admin_id bigint NOT NULL,
    action varchar(50) NOT NULL,
    target_id varchar(100) NOT NULL,
    occurred_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT fk_audit_workspace_owner FOREIGN KEY (workspace_id, actor_admin_id)
        REFERENCES workspaces(id, owner_admin_id)
);
CREATE INDEX idx_admin_audit_scope ON admin_audit (workspace_id, occurred_at);

-- Keep public IDs as exact JSON numbers without exposing shared sequence counters.
-- Reserve IDs transactionally so two concurrent writers cannot commit a collision.
CREATE TABLE allocated_public_ids (id bigint PRIMARY KEY);
CREATE FUNCTION allocate_public_id() RETURNS bigint
LANGUAGE plpgsql VOLATILE AS $$
DECLARE
    random_hex text;
    candidate bigint;
BEGIN
    LOOP
        random_hex := replace(gen_random_uuid()::text, '-', '');
        -- Skip the UUID version nibble. 52 random bits fit a JavaScript safe integer.
        candidate := ('x' || substr(random_hex, 1, 12) || substr(random_hex, 14, 1))::bit(52)::bigint + 1;
        INSERT INTO allocated_public_ids (id) VALUES (candidate) ON CONFLICT DO NOTHING;
        IF FOUND THEN RETURN candidate; END IF;
    END LOOP;
END
$$;

ALTER TABLE usb_devices ALTER COLUMN id DROP IDENTITY, ALTER COLUMN id SET DEFAULT allocate_public_id();
ALTER TABLE usb_events ALTER COLUMN id DROP IDENTITY, ALTER COLUMN id SET DEFAULT allocate_public_id(),
    ADD COLUMN ingest_order bigint GENERATED ALWAYS AS IDENTITY;
ALTER TABLE endpoint_whitelist_entries ALTER COLUMN id DROP IDENTITY, ALTER COLUMN id SET DEFAULT allocate_public_id();
ALTER TABLE admin_audit ALTER COLUMN id DROP IDENTITY, ALTER COLUMN id SET DEFAULT allocate_public_id();
CREATE INDEX idx_event_workspace_time ON usb_events (workspace_id, occurred_at DESC, ingest_order DESC);
